// Generates src/styles/zoom-type.css. Run with: npm run zoom-type
//
// On screens wider than 1440px the page is scaled up as a whole (src/support/devicePolish.ts),
// so inside it the layout is always 1440px wide. Font sizes written as clamp(min, Nvw, max)
// still read vw from the real screen, though, and grow past their 1440px value — headlines
// then wrap onto an extra line. This script finds those clamps and pins each one to its
// 1440px size while the page is scaled (html.sv-zoomed). Re-run it after editing such a clamp.
import fs from "node:fs";
import { execSync } from "node:child_process";
import postcss from "postcss";

const DESIGN_WIDTH = 1440;
const OUT = "src/styles/zoom-type.css";
const files = execSync('git ls-files "*.css"')
  .toString()
  .trim()
  .split(/\r?\n/)
  .filter((f) => f && f !== OUT && !/iris-theme|visual-quality/.test(f));

const px = (v) => {
  v = v.trim();
  let m;
  if ((m = v.match(/^(-?[\d.]+)px$/))) return +m[1];
  if ((m = v.match(/^(-?[\d.]+)vw$/))) return (+m[1] * DESIGN_WIDTH) / 100;
  if ((m = v.match(/^(-?[\d.]+)rem$/))) return +m[1] * 16;
  return null;
};

// Put .sv-zoomed on the root element of each selector, inside :where() so the rule keeps the
// original's specificity: it overrides that rule (it loads later) but never a stronger one.
const scope = (sel) =>
  sel
    .split(",")
    .map((s) => {
      s = s.trim().replace(/\s+/g, " ");
      if (/^html(?=[.:[\s]|$)/.test(s)) return s.replace(/^html/, "html:where(.sv-zoomed)");
      if (/^:root/.test(s)) return s.replace(/^:root/, ":root:where(.sv-zoomed)");
      return `:where(html.sv-zoomed) ${s}`;
    })
    .join(",\n");

const blocks = new Map(); // media params -> rules
for (const file of files) {
  postcss.parse(fs.readFileSync(file, "utf8")).walkDecls((decl) => {
    if (!/^(font-size|font)$/.test(decl.prop) || !/clamp\(/.test(decl.value) || !/vw/.test(decl.value)) return;
    const media = [];
    for (let p = decl.parent.parent; p; p = p.parent) if (p.type === "atrule" && p.name === "media") media.push(p.params);
    const max = media.join(" ").match(/max-width:\s*(\d+)/);
    if (max && +max[1] < DESIGN_WIDTH) return; // only active below the design width
    const m = decl.value.match(/clamp\(\s*([^,]+),\s*([^,]+),\s*([^)]+)\)/);
    if (!m) return;
    const [lo, mid, hi] = m.slice(1).map(px);
    if ([lo, mid, hi].includes(null)) return;
    const at1440 = Math.min(hi, Math.max(lo, mid));
    // Clamps already at their cap are pinned too (same size), so rules of equal specificity
    // keep their original order relative to each other.
    const key = media.join(" and ");
    if (!blocks.has(key)) blocks.set(key, []);
    blocks.get(key).push(`/* ${file} */\n${scope(decl.parent.selector)} { font-size: ${+at1440.toFixed(3)}px; }`);
  });
}

let css = `/* GENERATED by scripts/zoom-type.mjs — do not edit by hand; run \`npm run zoom-type\`.
   While the page is scaled up on wide screens, vw-based font clamps keep their 1440px size. */\n`;
for (const [media, rules] of blocks) {
  css += media ? `\n@media ${media} {\n${rules.join("\n").replace(/^/gm, "  ")}\n}\n` : `\n${rules.join("\n")}\n`;
}
fs.writeFileSync(OUT, css);
console.log(`${OUT}: ${[...blocks.values()].flat().length} rules`);
