import { mkdirSync } from 'node:fs';
mkdirSync('test-results', { recursive: true });
import { chromium } from '@playwright/test';
import assert from 'node:assert/strict';
const browser = await chromium.launch({channel:'chrome',headless:true});
const page = await browser.newPage();
const errors = [];
const base = process.env.BASE_URL || 'http://127.0.0.1:5176';
page.on('pageerror', e => errors.push(e.message));
await page.goto(base);
await page.getByRole('heading', {level:1}).waitFor();
for (const [name,width,height] of [['desktop',1450,1000],['tablet',820,1180],['mobile',390,844]]) {
  await page.setViewportSize({width,height});
  await page.screenshot({path:`test-results/${name}.png`,fullPage:true});
  assert(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), `${name} overflow`);
}
await page.setViewportSize({width:1450,height:1000});
await page.getByRole('button',{name:'Mở menu',exact:true}).click();
assert(await page.getByRole('button',{name:'Tin tức',exact:true}).first().isVisible());
await page.keyboard.press('Escape');
assert.equal(await page.getByRole('button',{name:'Mở menu',exact:true}).getAttribute('aria-expanded'),'false');
await page.getByRole('tab',{name:'Nhận diện tiền',exact:true}).click();
assert(await page.getByText('Đây là tờ tiền mệnh giá năm mươi nghìn đồng.',{exact:true}).isVisible());
await page.keyboard.press('ArrowRight');
assert.equal(await page.getByRole('tab',{name:'Mô tả xung quanh',exact:true}).getAttribute('aria-selected'),'true');
await page.getByRole('button',{name:'Trao đổi về trải nghiệm',exact:true}).click();
await page.waitForURL('**/lien-he');
await page.goto(base);
await page.evaluate(()=>scrollTo(0,200));
await page.mouse.move(650,250);
await page.waitForTimeout(100);
let coordinates = await page.locator('.hero').evaluate(el => ({x:parseFloat(el.style.getPropertyValue('--lx')),y:parseFloat(el.style.getPropertyValue('--ly')),top:el.getBoundingClientRect().top,left:el.getBoundingClientRect().left}));
assert.equal(coordinates.x,650-coordinates.left); assert.equal(coordinates.y,250-coordinates.top);
await page.setViewportSize({width:1100,height:800});
await page.mouse.move(500,300); await page.waitForTimeout(100);
coordinates = await page.locator('.hero').evaluate(el => ({x:parseFloat(el.style.getPropertyValue('--lx')),y:parseFloat(el.style.getPropertyValue('--ly')),top:el.getBoundingClientRect().top,left:el.getBoundingClientRect().left}));
assert.equal(coordinates.x,500-coordinates.left); assert.equal(coordinates.y,300-coordinates.top);
await page.mouse.move(500,790);
await page.evaluate(()=>scrollTo(0,0));
await page.mouse.move(10,10); await page.waitForTimeout(100);
const last = await page.locator('.hero').getAttribute('style');
await page.waitForTimeout(2700);
assert.equal(await page.locator('.hero').getAttribute('style'),last);
await page.emulateMedia({reducedMotion:'reduce'});
await page.mouse.move(600,400); await page.waitForTimeout(100);
assert.equal(await page.locator('.hero').evaluate(el=>el.style.getPropertyValue('--lx')),'66%');
await page.screenshot({path:'test-results/reduced-motion.png'});
assert.equal(await page.locator('h1').count(),1);
assert.deepEqual(errors,[]);
const touch = await browser.newContext({viewport:{width:390,height:844},isMobile:true,hasTouch:true});
const mobile = await touch.newPage(); await mobile.goto(base);
await mobile.locator('.hero').dispatchEvent('pointermove',{pointerType:'touch',clientX:100,clientY:150});
assert.equal(await mobile.locator('.hero').evaluate(el=>el.style.getPropertyValue('--lx')),'');
await browser.close();
console.log('Passed: three responsive widths, menu/Escape, keyboard tabs, Contact navigation, pointer coordinates after scroll/resize, retained glow, reduced motion, touch, single h1, no runtime errors.');
